/**
 * Stands in for graphql-codegen, for the ported rcm-dashboard only.
 *
 * `src/features/rcm-dashboard` is byte-identical to upstream, so it imports
 * hooks by the exact names codegen emits. Codegen output is not committed
 * upstream, so rather than hand-write thirty hooks and drift from the
 * documents, this reads the feature's own .graphql files and emits one hook
 * per operation, with the same naming rule codegen uses:
 *
 *   query GetFoo   ->  GetFooDocument, useGetFooQuery, useGetFooLazyQuery
 *   mutation SetFoo ->  SetFooDocument, useSetFooMutation
 *
 *   node scripts/gen-dashboard-hooks.mjs
 */
import fs from "node:fs";
import path from "node:path";

const FEATURE = "src/features/rcm-dashboard/graphql";
const OUT = "src/vendor/app/generated-dashboard.ts";

const files = fs
  .readdirSync(FEATURE)
  .filter((f) => f.endsWith(".graphql"))
  .sort();

/** Split a .graphql file into top-level operations, brace-counting. */
function operations(src) {
  const ops = [];
  const re = /^(query|mutation|subscription)\s+([A-Za-z0-9_]+)/gm;
  let m;
  while ((m = re.exec(src))) {
    const start = m.index;
    let i = src.indexOf("{", start);
    if (i < 0) continue;
    let depth = 0;
    for (; i < src.length; i += 1) {
      if (src[i] === "{") depth += 1;
      else if (src[i] === "}") {
        depth -= 1;
        if (depth === 0) break;
      }
    }
    ops.push({ kind: m[1], name: m[2], body: src.slice(start, i + 1) });
  }
  return ops;
}

const all = [];
for (const f of files) {
  const src = fs.readFileSync(path.join(FEATURE, f), "utf8");
  for (const op of operations(src)) all.push({ ...op, file: f });
}

const seen = new Set();
const unique = all.filter((o) => !seen.has(o.name) && seen.add(o.name));

const head = `/**
 * Generated by scripts/gen-dashboard-hooks.mjs. Do not edit by hand.
 *
 * One hook per operation in src/features/rcm-dashboard/graphql/*.graphql,
 * named the way graphql-codegen names them, so the ported feature (which is
 * byte-identical to upstream) imports them unchanged.
 *
 * Regenerate with: npm run gen:hooks
 */
import { gql, useQuery, useLazyQuery, useMutation } from "@apollo/client";

`;

const parts = [head];
for (const op of unique) {
  parts.push(`export const ${op.name}Document = gql\`\n${op.body.replace(/`/g, "\\`")}\n\`;\n\n`);
}
parts.push("/* ── hooks ─────────────────────────────────────────────────────────────── */\n\n");
for (const op of unique) {
  if (op.kind === "mutation") {
    parts.push(
      `export const use${op.name}Mutation = (opts?: any) => useMutation(${op.name}Document, opts);\n`,
    );
  } else {
    parts.push(
      `export const use${op.name}Query = (opts?: any) => useQuery(${op.name}Document, opts);\n` +
        `export const use${op.name}LazyQuery = (opts?: any) => useLazyQuery(${op.name}Document, opts);\n`,
    );
  }
}

/**
 * Types and enums the feature imports alongside the hooks. Codegen derives
 * these from the schema; the handful the dashboard actually names are listed
 * here rather than generated, because they are used as TypeScript types only.
 */
parts.push(`
/* ── types and enums the feature imports ───────────────────────────────── */

export interface QueueDashboardFilterInput {
  fromDate?: string | null;
  toDate?: string | null;
  vendorId?: string | null;
  workItemTypes?: string[] | null;
  teamIds?: string[] | null;
  branches?: string[] | null;
}

export interface QueueDashboardAgingRangeInput {
  fromDays?: number | null;
  toDays?: number | null;
}

export type QueueDashboardMemberRow = any;
export type QueueDashboardOverduePending = any;
export type QueueDashboardMemberViewQuery = any;
export type GetUnassignedAuthorizationsQuery = any;
export type GetUnassignedValidationRequestsQuery = any;

export const WorkItemType = {
  Reconciliation: "RECONCILIATION",
  ClaimSubmission: "CLAIM_SUBMISSION",
  ClaimResubmission: "CLAIM_RESUBMISSION",
  ClaimValidation: "CLAIM_VALIDATION",
  AuthorizationSubmission: "AUTHORIZATION_SUBMISSION",
  AuthorizationResubmission: "AUTHORIZATION_RESUBMISSION",
} as const;
export type WorkItemType = (typeof WorkItemType)[keyof typeof WorkItemType];

export const VendorUserTypes = {
  Coder: "CODER",
  Submitter: "SUBMITTER",
  Supervisor: "SUPERVISOR",
} as const;
export type VendorUserTypes = (typeof VendorUserTypes)[keyof typeof VendorUserTypes];
`);


/**
 * App-wide operations the dashboard calls that are not declared in its own
 * .graphql files, so codegen picks them up from elsewhere in the monorepo.
 * Written out here with the same names, backed by the local schema.
 */
parts.push(`
/* ── app-wide operations, declared outside the feature ── */

const MeDocument = gql\`
  query Me {
    allUsers { id firstName lastName email }
  }
\`;

/** The signed-in user. One local user stands in for the session. */
const useMe = (opts?: any) => {
  const r = useQuery(MeDocument, opts);
  const me = r.data?.allUsers?.[0];
  return {
    ...r,
    data: me
      ? {
          me: { ...me, name: [me.firstName, me.lastName].filter(Boolean).join(" ") },
          currentUser: me,
        }
      : undefined,
  };
};
export const useMeQuery = useMe;
export const useGetCurrentUserQuery = useMe;

export const GetRcmUsersDocument = gql\`
  query GetRcmUsers($first: Int, $after: String, $filter: UserFilterInput) {
    rcmUsers(first: $first, after: $after, filter: $filter) {
      edges { node { id firstName lastName email } cursor }
      pageInfo { hasNextPage endCursor }
      totalCount
    }
  }
\`;
export const useGetRcmUsersQuery = (opts?: any) => useQuery(GetRcmUsersDocument, opts);

/**
 * Assignment is read-only here. The dashboard can show what the nightly run
 * did and who is loaded; actually moving work is the workflow's job, and this
 * app configures and observes rather than allocates.
 */
const noopMutation = () => [
  async () => ({ data: null }),
  { loading: false, error: undefined, data: undefined, called: false, reset: () => {} },
];
export const useAssignWorkItemsMutation = noopMutation as any;
export const useSelfAssignValidationRequestMutation = noopMutation as any;

export const GetDashboardActivityDocument = gql\`
  query GetDashboardActivity($first: Int) {
    optimaAllocationRuns(first: $first) {
      id
      startedAt
      failed
      totals { ranked assigned unmatched }
    }
  }
\`;
/** Recent activity, from the allocation run log rather than claim submissions. */
export const useGetDashboardActivityQuery = (opts?: any) =>
  useQuery(GetDashboardActivityDocument, opts);

const DenialStatsDocument = gql\`
  query GetDenialStats {
    optimaLatestAllocationRun { totals { ranked assigned unmatched } }
  }
\`;
/**
 * Denial rate. Upstream this counts rejected claims; the closest honest local
 * figure is the share of ranked work that no group would take, which is the
 * number a supervisor is actually chasing here.
 */
export const useGetDenialStatsQuery = (opts?: any) => {
  const r = useQuery(DenialStatsDocument, opts);
  const t = r.data?.optimaLatestAllocationRun?.totals;
  return {
    ...r,
    data: t
      ? {
          rejectedClaims: { totalCount: t.unmatched },
          totalClaims: { totalCount: t.ranked },
        }
      : undefined,
  };
};
`);

fs.writeFileSync(OUT, parts.join(""));
console.log(`${unique.length} operations from ${files.length} file(s) -> ${OUT}`);
for (const f of files) {
  const n = all.filter((o) => o.file === f).length;
  console.log(`  ${f}: ${n}`);
}
